/**
 * Generation + chronic problems for a specific car year. Falls back to the
 * catalogue's main generation when the year isn't covered by GENERATIONS.
 */
export function generationInfo(modelId: string, year?: number) {
  const m = getModel(modelId);
  const g = generationFor(modelId, year);
  if (g) return { name: g.name, years: g.years, problems: g.problems, specific: true };
  return { name: m?.generation ?? "", years: m?.years ?? [0, 0], problems: m?.problems ?? [], specific: false };
}

/** All generations we know for a model, oldest first ("W210 · W211 · W212 · W213") */
export function generationNames(modelId: string) {
  const m = getModel(modelId);
  const list = [...(GENERATIONS[modelId] ?? []).map((g) => ({ n: g.name, y: g.years[0] })), ...(m ? [{ n: m.generation, y: m.years[0] }] : [])];
  return list.sort((a, b) => a.y - b.y).map((g) => g.n).join(" · ");
}
